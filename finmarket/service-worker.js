/* Финмаркет — service worker.
 *
 * Что он делает:
 *  1. При установке кладёт оболочку приложения в кэш.
 *  2. data.json тянет по правилу «сеть, при отказе кэш».
 *  3. Если отдал data.json ИЗ КЭША — помечает ответ заголовками, и витрина
 *     обязана напечатать «данные от <дата>, сети нет». Молча старые цифры
 *     показывать нельзя.
 *  4. Версия кэша — в одной константе ниже. При активации всё, что помечено
 *     как «finmarket-» и не относится к текущей версии, удаляется.
 *  5. Сам себя не кэширует: запрос за service-worker.js через кэш не идёт.
 */

/* Версия кэша и версия схемы data.json меняются СОГЛАСОВАННО (В-38, RULES.md 4б).
 * Иначе у установленного приложения новый data.json придёт по сети, а старый
 * app.js останется из кэша оболочки, и экран сломается у пользователя.
 *   v2 -> схема 3 (справочник причин, восемь классов)
 *   v3 -> схема 4 (базы сравнения из 02_data/finmarket.db, узел «база_данных»)
 *   v4 -> схема 5 (gcb и gold тоже из базы; демо=false, снята демо-полоса;
 *                  узел «база_данных» — по каждому классу; поля Р-25/Р-28)
 *   v5 -> схема 6 (у macro прогон свой на каждый показатель: курсы
 *                  ежедневно, ИПЦ раз в месяц — общего прогона нет) */
const ВЕРСИЯ = 'v61';
const СХЕМА_ДАННЫХ = 44;

/* v25 — СХЕМА ДАННЫХ ТА ЖЕ, 24: переписан экран, а не формат.
 *
 * Эти две константы меняются согласованно, но они не одно и то же.
 * СХЕМА_ДАННЫХ обязана совпасть с полем «схема» в data.json — это
 * договор между витриной и сборкой. ВЕРСИЯ — имя кэша оболочки; её
 * поднимают всякий раз, когда меняется САМА ОБОЛОЧКА, даже если данные
 * остались прежними. Здесь именно такой случай: index.html, app.css
 * и app.js переписаны целиком, а data.json не тронут. Не подними мы
 * ВЕРСИЮ — у всех, кто уже поставил приложение, остался бы старый
 * экран из кэша при новых файлах на сайте.
 *
 * v26 -> схема 25. Здесь меняется уже и формат смысла: решение Р-95
 * перевернуло границу корзин сроков. Вклад ровно на год лежит теперь
 * в «до года», а не в «до двух лет». Сами поля данных прежние, но
 * старый data.json с новым экраном показал бы чипу «1 год» содержимое,
 * собранное по прежнему правилу, — то самое противоречие, ради
 * устранения которого правило и переворачивали. Поэтому поднимается
 * не только версия кэша, но и схема: старые данные не должны подойти.
 *
 * v27 -> схема та же, 25. Правки после проверки на телефоне: отступ под
 * нижней панелью, перенос в главной цифре карточки, кольцо фокуса
 * на крестике, валюта у минимальной суммы. Менялись только файлы
 * оболочки. Телефон, на котором уже стоял v26, честно отдал старые
 * app.css и app.js из кэша — и правок на экране не было видно.
 * Это не поломка, это В-38 в действии: оболочка меняется вместе
 * с версией, и другого способа её обновить нет.
 *
 * v28 -> схема та же, 25. Приложение теперь обновляется САМО: новый
 * service worker сообщает окнам свою версию, и страница перезагружается
 * один раз на смену версии. Плюс пункт «Условия использования»
 * в разделе «Ещё» (Р-96). Менялись только файлы оболочки.
 *
 * v29 -> схема та же, 25. Новая иконка приложения (Р-102): купюра
 * вместо трёх столбиков. Столбики повторяли знак соседнего проекта —
 * владелец увидел это на телефоне, где иконки стоят рядом. Иконки
 * входят в оболочку, поэтому версия поднимается: иначе установленное
 * приложение показывало бы прежний значок из кэша.
 *
 * v30 -> схема та же, 25. Иконка сменена на вариант «купюра со знаком
 * сома» — выбор владельца. Версия поднята по той же причине, что и v29:
 * иконки лежат в кэше оболочки.
 *
 * v31 -> схема 26. У пустых классов появился узел «подготовлено»: что
 * именно там будет показано, когда источник подключат (Р-101, места
 * под криптовалюту, облигации и аренду). Изменились и названия корзин
 * сроков — прежние врали на нижней границе. Форма данных выросла,
 * поэтому схема и версия кэша поднимаются вместе.
 *
 * v32 -> схема та же, 26. Логотипы вернулись в список бессрочных
 * вкладов: там всегда рисовалась монограмма, даже когда знак банка
 * лежал рядом в кэше. Доллар и инфляция поменялись местами и залиты
 * обе одинаково. Менялись только файлы оболочки.
 *
 * v33 -> схема 27. На витрину вышел класс «Вклады МФК» (Р-104):
 * у класса появились узлы «со_ставкой» и «без_ставки», а строки
 * без ставки получили честную причину вместо домысла. Форма данных
 * выросла — схема и версия кэша поднимаются вместе. */

/* v23 — схема данных та же (23), но изменился состав оболочки: пути
 * стали относительными к папке SW. Старый кэш с корневыми путями надо
 * выбросить, иначе установленное приложение осталось бы с ними. */
const КЭШ_ОБОЛОЧКИ = 'finmarket-shell-' + ВЕРСИЯ;
const КЭШ_ДАННЫХ = 'finmarket-data-' + ВЕРСИЯ;
const СВОИ_КЭШИ = [КЭШ_ОБОЛОЧКИ, КЭШ_ДАННЫХ];

/* БАЗА — папка, в которой лежит сам service worker.
 *
 * Раньше пути были прибиты к корню домена ('/index.html', '/data.json').
 * Это работает, только пока витрина лежит в корне. По решению Р-83 она
 * выложена в /finmarket/, и прибитые пути кэшировали бы чужой корень,
 * а data.json просто не находился бы: 404 вместо цифр.
 *
 * Теперь база берётся у самого SW: он лежит рядом с index.html, значит
 * его папка и есть папка витрины. Один и тот же файл работает и в корне
 * (локальный сервер), и в подпапке (GitHub Pages) — без правок и без
 * переменной, которую надо не забыть поменять при переезде. */
const БАЗА = new URL('./', self.location).pathname;

/* Оболочка: всё, без чего экран не нарисуется. Данных здесь нет. */
const ОБОЛОЧКА = [
  БАЗА,
  БАЗА + 'index.html',
  БАЗА + 'app.css',
  БАЗА + 'app.js',
  БАЗА + 'yazyk.js',
  БАЗА + 'ky.json',
  БАЗА + 'manifest.webmanifest',
  БАЗА + 'icon-192.png',
  БАЗА + 'icon-512.png',
  БАЗА + 'icon-512-maskable.png',
  БАЗА + 'logos/spisok.json'
];

/* Логотипы банков (Р-89) лежат в приложении и обязаны быть в кэше:
 * подтягивать их с сайтов банков нельзя — офлайн кружки остались бы
 * пустыми, а офлайн здесь обычный режим, а не редкость.
 *
 * Перечень не вписан сюда руками: имена файлов зависят от того, в каком
 * формате банк опубликовал свой знак, и один переименованный файл сделал
 * бы addAll целиком неуспешным — приложение осталось бы вообще без кэша
 * из-за одной картинки. Список читается из spisok.json, и каждый файл
 * кладётся ОТДЕЛЬНО: не взялся один — у этого банка будет монограмма,
 * что Р-89 прямо разрешает, а остальные пятнадцать на месте. */
async function положитьЛоготипы(c) {
  try {
    const о = await fetch(БАЗА + 'logos/spisok.json', { cache: 'no-store' });
    if (!о.ok) return;
    const список = await о.json();
    await Promise.all(Object.keys(список).map(function (ключ) {
      return c.add(БАЗА + 'logos/' + список[ключ].файл).catch(function () {});
    }));
  } catch (e) {
    /* Нет списка — нет логотипов, монограммы на месте. Установку
     * приложения это срывать не должно. */
  }
}

const ПУТЬ_ДАННЫХ = БАЗА + 'data.json';
const ПУТЬ_SW = БАЗА + 'service-worker.js';

/* ------------------------------------------------------------ установка */

self.addEventListener('install', function (e) {
  e.waitUntil((async function () {
    const c = await caches.open(КЭШ_ОБОЛОЧКИ);
    /* Каждый файл оболочки — В ОБХОД HTTP-кэша и с меткой версии в адресе,
     * а в кэш кладётся под своим обычным адресом. Найдено на телефоне
     * 25.09.2026: addAll взял app.js из HTTP-кэша браузера (GitHub Pages
     * отдаёт max-age=600), и в оболочку v51 легла прежняя версия файла —
     * калькулятор был, строки «для населения» не было. Метка версии даёт
     * CDN новый адрес, «reload» — мимо кэша браузера. */
    for (const адрес of ОБОЛОЧКА) {
      const свежий = адрес + (адрес.indexOf('?') < 0 ? '?' : '&') + 'v=' + ВЕРСИЯ;
      const о = await fetch(свежий, { cache: 'reload' });
      if (!о.ok) throw new Error('obolochka: ' + адрес + ' -> ' + о.status);
      await c.put(адрес, о);
    }
    await положитьЛоготипы(c);

    /* Попутно, но НЕ обязательно: если сеть сейчас есть, сразу положим
     * данные в кэш. Иначе первый же офлайн-запуск остался бы без цифр.
     * Отказ здесь установку не срывает. */
    try {
      const r = await fetch(ПУТЬ_ДАННЫХ, { cache: 'no-store' });
      if (r && r.ok) await сохранитьДанные(r.clone());
    } catch (err) {
      /* сети нет — переживём, витрина объяснит это сама */
    }

    await self.skipWaiting();
  })());
});

/* ------------------------------------------------------------ активация */

self.addEventListener('activate', function (e) {
  e.waitUntil((async function () {
    const ключи = await caches.keys();
    for (const к of ключи) {
      if (к.indexOf('finmarket-') === 0 && СВОИ_КЭШИ.indexOf(к) === -1) {
        await caches.delete(к);
      }
    }
    await self.clients.claim();

    /* НОВАЯ ВЕРСИЯ ВКЛЮЧАЕТСЯ САМА (Р-96 не про это; это находка
     * с телефона владельца).
     *
     * `skipWaiting` и `clients.claim` делают новый service worker
     * управляющим сразу — но УЖЕ ОТКРЫТАЯ страница продолжает жить
     * с теми app.css и app.js, которые получила при загрузке. Файлы
     * в кэше новые, а на экране старые, и человек об этом не знает.
     * В проверке это чинилось перезагрузкой из скрипта; у живого
     * человека скрипта нет.
     *
     * Поэтому здесь мы говорим страницам, какая версия встала. Решение
     * перезагружаться принимает страница: только она знает, был ли
     * у неё управляющий раньше (при первой установке перезагружаться
     * не из-за чего) и не перезагружалась ли она уже под эту версию.
     *
     * Версия передаётся ЗНАЧЕНИЕМ, а не как «обновись»: сообщение
     * «обновись» нельзя отличить от повторного, и на нём легко
     * закольцеваться. Версию можно сравнить с прошлой. */
    const окна = await self.clients.matchAll({ type: 'window',
                                               includeUncontrolled: true });
    for (const окно of окна) {
      окно.postMessage({ тип: 'новая-версия', версия: ВЕРСИЯ });
    }
  })());
});

/* ------------------------------------------------------------ данные */

async function сохранитьДанные(ответ) {
  const c = await caches.open(КЭШ_ДАННЫХ);
  const тело = await ответ.arrayBuffer();
  const h = new Headers(ответ.headers);
  /* когда именно этот слепок лёг в кэш — витрина покажет это в полосе */
  h.set('X-Cached-At', new Date().toISOString());
  await c.put(ПУТЬ_ДАННЫХ, new Response(тело, { status: 200, headers: h }));
}

async function данные(запрос) {
  /* сеть первой */
  try {
    const сеть = await fetch(запрос, { cache: 'no-store' });
    if (сеть && сеть.ok) {
      await сохранитьДанные(сеть.clone());
      return сеть;
    }
    throw new Error('HTTP ' + (сеть ? сеть.status : '?'));
  } catch (err) {
    /* сети нет — отдаём кэш, но ПОМЕЧЕННЫЙ */
    const c = await caches.open(КЭШ_ДАННЫХ);
    const из_кэша = await c.match(ПУТЬ_ДАННЫХ);

    if (из_кэша) {
      const тело = await из_кэша.arrayBuffer();
      const h = new Headers(из_кэша.headers);
      h.set('X-From-Cache', '1');
      h.set('X-Fm-Reason', 'network-failed');
      return new Response(тело, { status: 200, headers: h });
    }

    /* ни сети, ни кэша — честный отказ с причиной, а не пустой экран */
    return new Response(
      JSON.stringify({ ошибка: 'нет-данных', причина: String(err) }),
      {
        status: 504,
        headers: {
          'Content-Type': 'application/json; charset=utf-8',
          'X-Fm-Reason': 'no-network-no-cache'
        }
      }
    );
  }
}

/* ------------------------------------------------------------ оболочка */

async function оболочка(запрос) {
  const из_кэша = await caches.match(запрос);
  if (из_кэша) return из_кэша;
  try {
    const сеть = await fetch(запрос);
    if (сеть && сеть.ok && новый_URL(запрос).origin === self.location.origin) {
      const c = await caches.open(КЭШ_ОБОЛОЧКИ);
      await c.put(запрос, сеть.clone());
    }
    return сеть;
  } catch (err) {
    /* переход по адресу без сети — отдаём сохранённую страницу */
    if (запрос.mode === 'navigate') {
      const стр = await caches.match(БАЗА + 'index.html');
      if (стр) return стр;
    }
    throw err;
  }
}

function новый_URL(запрос) {
  return new URL(запрос.url);
}

/* ------------------------------------------------------------ перехват */

self.addEventListener('fetch', function (e) {
  const запрос = e.request;
  if (запрос.method !== 'GET') return;

  const u = new URL(запрос.url);
  if (u.origin !== self.location.origin) return;

  /* сам service worker мимо кэша, всегда из сети */
  if (u.pathname === ПУТЬ_SW) return;

  if (u.pathname === ПУТЬ_ДАННЫХ) {
    e.respondWith(данные(запрос));
    return;
  }

  e.respondWith(оболочка(запрос));
});
