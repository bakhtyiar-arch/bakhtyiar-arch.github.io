  /* Очередь продавцов слитка. Порядок приезжает ИЗ ДАННЫХ (решение
   * владельца «НБКР выше»), а не записан здесь второй раз: два списка
   * в двух местах разойдутся на первой же правке, и разойдутся молча.
   *
   * Продавец, которого в перечне нет, встаёт после названных — но
   * встаёт. Цена, пропавшая с экрана, хуже цены от незнакомой лавки. */
  function продавцыЗолота(k) {
    var порядок = k.порядок_продавцов || [];
    var были = [];
    (k.инструменты || []).forEach(function (i) {
      var пр = i.продавец || 'продавец не опознан';
      if (были.indexOf(пр) < 0) были.push(пр);
    });
    /* Сравнение, а не вычитание. Разность мест дала бы тот же порядок,
     * но витрина считать не вправе (Р-85), и сторож арифметики поймал
     * это сразу. Правило не про эту строку — оно про то, что единственное
     * место расчёта на витрине должно оставаться единственным. */
    были.sort(function (a, b) {
      var па = порядок.indexOf(a), пб = порядок.indexOf(b);
      if (па < 0) па = порядок.length;
      if (пб < 0) пб = порядок.length;
      if (па < пб) return -1;
      return па > пб ? 1 : 0;
    });
    return были;
  }

