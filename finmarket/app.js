  function отДо(от, до, ед) {
    var есть = function (x) { return x !== null && x !== undefined; };
    if (есть(от) && есть(до) && от !== до) return число(от) + '–' + число(до) + ед;
    if (есть(от)) return (есть(до) ? '' : 'от ') + число(от) + ед;
    if (есть(до)) return 'до ' + число(до) + ед;
    return null;
  }

