  /* Порядок списка вкладов: по ставке, больше — выше; без ставки — вниз.
   * При РАВНОЙ ставке банки из перечня `при_равной_ставке_после` идут
   * после остальных (решение владельца 24.09.2026). Перечень — из данных,
   * тот же, по которому сборка выбирает вклад, названный лучшим.
   * Сортировка устойчивая: прочие равные остаются в порядке данных. */
  function порядокПоСтавке(a, b) {
    if (a.ставка === null && b.ставка === null) return 0;
    if (a.ставка === null) return 1;
    if (b.ставка === null) return -1;
    if (a.ставка !== b.ставка) return a.ставка < b.ставка ? 1 : -1;
    var после = (Д && Д.при_равной_ставке_после) || [];
    var па = после.indexOf(a.банк_кратко) >= 0, пб = после.indexOf(b.банк_кратко) >= 0;
    return па === пб ? 0 : (па ? 1 : -1);
  }

