  /* КАЛЬКУЛЯТОР (решение владельца 25.09.2026) — ИСКЛЮЧЕНИЕ ИЗ Р-05.
   * Считает из числа, которое ввёл ЧЕЛОВЕК (сумма), и из условий продукта
   * в data.json (ставка, срок). Опубликованные цифры по-прежнему готовые:
   * ни одна цифра экрана калькулятором не пересчитывается. Итог —
   * «примерный расчёт».
   *   вклад:  с ежемесячной капитализацией — S·(1 + r/1200)^n,
   *           без неё или если банк не сказал — S·(1 + r/100 · n/12);
   *   кредит: ежемесячный платёж — аннуитет по номинальной «от»,
   *           S·i / (1 − (1 + i)^−n), i = r/1200; переплата — тем же
   *           аннуитетом по эффективной «от»: платёж·n − S. */
  function месяцевВклада(i) {
    if (i.срок_мес) return i.срок_мес;          /* общий калькулятор: введено месяцами */
    return i.срок_лет ? Math.round(i.срок_лет * 12) : null;
  }

  function расчётВклада(i, сумма) {
    var n = месяцевВклада(i), r = i.ставка;
    if (!n || r === null || r === undefined) return null;
    var итог = i.капитализация_ежемесячно
      ? сумма * Math.pow(1 + r / 1200, n)
      : сумма * (1 + r / 100 * n / 12);
    return { доход: Math.round(итог - сумма), итог: Math.round(итог), месяцев: n,
             капитализация: !!i.капитализация_ежемесячно };
  }

  function аннуитет(сумма, ставка, n) {
    var м = ставка / 1200;
    return м === 0 ? сумма / n : сумма * м / (1 - Math.pow(1 + м, -n));
  }

  function месяцевКредита(i) {
    return i.срок_до_мес || i.срок_от_мес || null;
  }

  function расчётКредита(i, сумма) {
    var n = месяцевКредита(i);
    if (!n || i.ном_от === null || i.ном_от === undefined) return null;
    var платёж = аннуитет(сумма, i.ном_от, n);
    var переплата = (i.эфф_от === null || i.эфф_от === undefined) ? null
      : аннуитет(сумма, i.эфф_от, n) * n - сумма;
    return { платёж: Math.round(платёж), месяцев: n,
             переплата: переплата === null ? null : Math.round(переплата) };
  }

  /* Облигация (Р-124): доход к погашению при покупке по номиналу —
   * купоны за срок, S·купон/100·лет (как пример Минфина: 100 000 сом
   * под 17 % на 2 года — 34 000); купон за период — S·купон/100/выплат. */
  function расчётОблигации(и, сумма) {
    if (!и.купон || !и.срок_лет) return null;
    var доход = сумма * и.купон / 100 * и.срок_лет;
    return { доход: Math.round(доход), итог: Math.round(сумма + доход),
             купон_раз: и.купонов_в_год ? Math.round(сумма * и.купон / 100 / и.купонов_в_год) : null };
  }

  /* Р-127. ГРАФИК ПЛАТЕЖЕЙ ПО КРЕДИТУ, по месяцам.
   *   аннуитет:          платёж постоянный — аннуитет(S, r, n); проценты —
   *                      остаток·r/1200, долг — платёж минус проценты;
   *   дифференцированный: долг гасится равными частями S/n, проценты —
   *                      с остатка, поэтому платёж с каждым месяцем меньше.
   * Последний месяц гасит остаток целиком: округление не оставляет
   * «хвоста» в копейках. */
  function графикКредита(сумма, ставка, n, вид) {
    n = Math.max(1, Math.round(n));          /* «12,5 месяца» — целых месяцев 13 */
    var м = ставка / 1200, остаток = сумма, ряды = [], всегоПроц = 0;
    var ан = вид === 'аннуитет' ? аннуитет(сумма, ставка, n) : null;
    for (var к = 1; к <= n; к++) {
      var проц = остаток * м;
      var долг = вид === 'аннуитет' ? ан - проц : сумма / n;
      if (к === n) долг = остаток;
      остаток -= долг;
      всегоПроц += проц;
      ряды.push({ номер: к, долг: Math.round(долг), проценты: Math.round(проц),
                  платёж: Math.round(долг + проц), остаток: Math.max(0, Math.round(остаток)),
                  доляДолга: долг + проц > 0 ? Math.round(долг / (долг + проц) * 1000) / 10 : 100 });
    }
    return { ряды: ряды, процентов: Math.round(всегоПроц), выплачено: Math.round(сумма + всегоПроц),
             первый: ряды[0].платёж, последний: ряды[n - 1].платёж };
  }

  /* Долгий кредит — по годам: 240 строк по месяцам никто не прочтёт.
   * Год — сумма долга и процентов его месяцев, остаток — на конец года. */
  function графикПоГодам(ряды) {
    var годы = [];
    ряды.forEach(function (р) {
      var г = Math.ceil(р.номер / 12);
      if (!годы[г - 1]) годы[г - 1] = { номер: г, долг: 0, проценты: 0, платёж: 0, остаток: 0 };
      var я = годы[г - 1];
      я.долг += р.долг; я.проценты += р.проценты; я.платёж += р.платёж; я.остаток = р.остаток;
    });
    годы.forEach(function (я) {
      я.доляДолга = я.платёж > 0 ? Math.round(я.долг / я.платёж * 1000) / 10 : 100;
    });
    return годы;
  }

  /* Р-127. РОСТ ВКЛАДА по месяцам: с капитализацией — S·(1 + r/1200)^k,
   * без неё — S·(1 + r/100 · k/12). Те же формулы, что расчётВклада. */
  function ростВклада(сумма, ставка, n, кап) {
    n = Math.max(1, Math.round(n));
    var ряды = [];
    for (var к = 1; к <= n; к++) {
      var итог = кап ? сумма * Math.pow(1 + ставка / 1200, к) : сумма * (1 + ставка / 100 * к / 12);
      ряды.push({ номер: к, вложено: Math.round(сумма), доход: Math.round(итог - сумма),
                  итог: Math.round(итог), доляВложено: Math.round(сумма / итог * 1000) / 10 });
    }
    return ряды;
  }

  /* Вклад по годам: конец каждого года и последний месяц срока. */
  function ростПоГодам(ряды) {
    return ряды.filter(function (р, н) { return р.номер % 12 === 0 || н === ряды.length - 1; })
      .map(function (р) {
        return { номер: Math.ceil(р.номер / 12), вложено: р.вложено, доход: р.доход,
                 итог: р.итог, доляВложено: р.доляВложено };
      });
  }

