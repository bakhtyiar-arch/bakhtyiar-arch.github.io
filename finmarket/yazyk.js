/* yazyk.js — выбор языка витрины: русский или кыргызский.
 *
 * В ОСНОВНОЙ ВИТРИНЕ с 26.09.2026 (решение владельца: отдельный просмотр
 * отменён). Переключатель «Кырг | Рус» — в шапке, по умолчанию русский;
 * перевод черновой, пока владелец не проверил строки таблицы.
 *
 * КАК РАБОТАЕТ
 *   - язык: выбор человека (запоминается в браузере); при первом запуске —
 *     язык телефона (navigator.languages начинается с «ky» — кыргызский)
 *     или язык по умолчанию из настроек страницы;
 *   - тексты: ky.json — «русский текст -> перевод». Запись — строка или
 *     {t: перевод, n: номер строки в таблице teksty_ky.xlsx}. Чего нет —
 *     остаётся по-русски;
 *   - «ключи»: рядом с каждым текстом из таблицы — маленький номер её
 *     строки, чтобы найти строку в Excel. Кнопка скрыта; показывается
 *     после пяти нажатий подряд на «Финмаркет» в шапке (ещё пять —
 *     снова прячется и выключает номера);
 *   - цифры не трогаются: числа и даты приходят из data.json как есть.
 *
 * Настройки — window.ЯЗЫК_НАСТРОЙКИ до подключения файла:
 *   { ключ: 'finmarket-yazyk', поУмолчанию: null, ключи: false, скрыт: false }
 * скрыт: true — переключателя нет, язык только русский (на случай, если
 * перевод не подтверждён к сроку).
 */
(function () {
  var Н = window.ЯЗЫК_НАСТРОЙКИ || {};
  var КЛЮЧ = Н.ключ || 'finmarket-yazyk';
  var КЛЮЧ_НОМЕРОВ = КЛЮЧ + '-klyuchi';
  var СЛОВАРЬ = null;
  var ШАБЛОНЫ = [];           // [{re: RegExp, t: перевод с {1}…, n: строка таблицы}]
  var ПРОМАХИ = {};           // строки без перевода (для проверки)
  var ИМЕНА = {};             // названия банков и продуктов: не переводятся никогда
  var ВЕРХНИЕ = '⁰¹²³⁴⁵⁶⁷⁸⁹';

  function прочитать(к) { try { return localStorage.getItem(к); } catch (e) { return null; } }
  function запомнить(к, з) { try { localStorage.setItem(к, з); } catch (e) { /* без памяти */ } }

  function языкТелефона() {
    var список = (navigator.languages && navigator.languages.length)
      ? navigator.languages : [navigator.language || ''];
    for (var н = 0; н < список.length; н++) {
      if (/^ky(\b|-|_)/i.test(список[н] || '')) return 'ky';
    }
    return 'ru';
  }

  var сохранён = прочитать(КЛЮЧ);
  var язык = Н.скрыт ? 'ru'
    : (сохранён === 'ru' || сохранён === 'ky') ? сохранён
    : (Н.поУмолчанию || языкТелефона());
  var доступКлючей = !Н.скрыт && (!!Н.ключи || прочитать(КЛЮЧ + '-dostup') === '1');
  var номера = доступКлючей && прочитать(КЛЮЧ_НОМЕРОВ) === '1';
  document.documentElement.lang = язык;

  function верхний(n) {
    return String(n).split('').map(function (ц) { return ВЕРХНИЕ[+ц] || ц; }).join('');
  }

  /* Шаблон: фраза, собранная из слов и чисел («+3,02 п.п. к инфляции»).
   * Места подстановки — {1}, {2}…; подставленное само переводится, если
   * оно есть в словаре («маю» -> «майга»). */
  function поШаблону(с, глубина) {
    for (var н = 0; н < ШАБЛОНЫ.length; н++) {
      var ш = ШАБЛОНЫ[н], м = ш.re.exec(с);
      if (!м) continue;
      var перевод = ш.t ? ш.t.replace(/\{(\d+)\}/g, function (_, и) {
        return вложенный((м[+и] || '').trim(), (глубина || 0) + 1);
      }) : null;
      return { t: перевод, n: ш.n };
    }
    return null;
  }

  /* Подставленное место переводится само: «Вклады МФК» в «{1} · что
   * нового», «2 сделки» внутри фразы про облигации. Имя банка или
   * продукта — никогда: «Автокредит» у Кыргызкоммерцбанка — название,
   * а не вид кредита. Глубина ограничена: шаблон в шаблоне в шаблоне. */
  function вложенный(ч, глубина) {
    if (!ч || язык !== 'ky' || ИМЕНА[ч] || глубина > 2) return ч;
    var зз = СЛОВАРЬ[ч];
    var т_ = зз && (typeof зз === 'string' ? зз : зз.t);
    if (т_) return т_;
    /* Перечень через «; » (банки со счётом вкладов, пометка «…; проверено
     * …») переводится по частям — раньше шаблона: иначе «{1} — {2} вкладов»
     * проглотит весь перечень и переведёт только последнее звено.
     * Непереведённая часть остаётся как есть. */
    if (ч.indexOf('; ') > 0) {
      return ч.split('; ').map(function (к) { return вложенный(к, глубина + 1); }).join('; ');
    }
    var ш = поШаблону(ч, глубина);
    return (ш && ш.t) || ч;
  }

  function т(ру) {
    if (ру === null || ру === undefined || !СЛОВАРЬ) return ру;
    var с = String(ру);
    if (ИМЕНА[с.trim()]) return ру;
    var з = СЛОВАРЬ[с] || СЛОВАРЬ[с.trim()];
    /* Точная строка без перевода — не повод сдаваться: у фразы сборки
     * с числами перевод живёт в шаблоне. */
    if (!з || (typeof з === 'object' && !з.t && язык === 'ky')) з = поШаблону(с.trim()) || з;
    if (!з) {
      if (/[А-Яа-яЁё]/.test(с)) ПРОМАХИ[с.trim()] = (ПРОМАХИ[с.trim()] || 0) + 1;
      return ру;
    }
    var перевод = typeof з === 'string' ? з : з.t;
    /* Пробелы по краям — часть разметки («2» + « сделки с 23.09»):
     * перевод встаёт между ними, иначе число слипается со словом. */
    var текст = (язык === 'ky' && перевод) ? с.match(/^\s*/)[0] + перевод + с.match(/\s*$/)[0] : с;
    if (номера && typeof з === 'object' && з.n) текст += ' ' + верхний(з.n);
    return текст;
  }

  /* Статичная разметка index.html: текстовые узлы и подписи aria-label. */
  function перевестиРазметку(корень) {
    if (!СЛОВАРЬ) return;
    var ходок = document.createTreeWalker(корень, NodeFilter.SHOW_TEXT);
    var у;
    while ((у = ходок.nextNode())) {
      var с = у.nodeValue;
      if (!с || !с.trim() || (у.parentElement && у.parentElement.closest('[data-bez-perevoda],script,style,noscript'))) continue;
      var п = т(с.trim());
      if (п !== с.trim()) у.nodeValue = с.replace(с.trim(), п);
    }
    [].forEach.call(корень.querySelectorAll('[aria-label]'), function (э) {
      if (!э.closest('[data-bez-perevoda]')) э.setAttribute('aria-label', т(э.getAttribute('aria-label')));
    });
  }

  /* Шапка: «Кырг | Рус» и скрытая кнопка «ключи». */
  function шапка() {
    var блок = document.querySelector('.yaz-pereklyuchatel');
    if (блок) {
      блок.hidden = !!Н.скрыт;
      [].forEach.call(блок.querySelectorAll('[data-yaz]'), function (b) {
        b.setAttribute('aria-pressed', язык === b.dataset.yaz ? 'true' : 'false');
        b.addEventListener('click', function () { if (язык !== b.dataset.yaz) ЯЗЫК.выбрать(b.dataset.yaz); });
      });
    }
    var кн = document.getElementById('shapka-klyuchi');
    if (кн) {
      кн.hidden = !доступКлючей;
      кн.setAttribute('aria-pressed', номера ? 'true' : 'false');
      кн.addEventListener('click', function () { ЯЗЫК.номера(!номера); });
    }
    var имя = document.getElementById('shapka-imya');
    if (!имя || Н.скрыт) return;
    var нажатий = 0, первое = 0;
    имя.addEventListener('click', function () {
      var сейчас = Date.now();
      if (сейчас - первое > 4000) { нажатий = 0; первое = сейчас; }
      if (++нажатий < 5) return;
      нажатий = 0;
      доступКлючей = !доступКлючей;
      запомнить(КЛЮЧ + '-dostup', доступКлючей ? '1' : '0');
      if (!доступКлючей && номера) { ЯЗЫК.номера(false); return; }
      if (кн) кн.hidden = !доступКлючей;
    });
  }

  window.ЯЗЫК = {
    текущий: function () { return язык; },
    источник: function () { return сохранён ? 'выбор' : (Н.поУмолчанию ? 'по умолчанию' : 'язык телефона'); },
    выбрать: function (я) {
      if (я !== 'ru' && я !== 'ky') return;
      запомнить(КЛЮЧ, я);
      location.reload();
    },
    номераВключены: function () { return номера; },
    ключиДоступны: function () { return доступКлючей; },
    номера: function (вкл) { запомнить(КЛЮЧ_НОМЕРОВ, вкл ? '1' : '0'); location.reload(); },
    /* Словарь нужен и по-русски, если включены номера строк. */
    загрузить: function () {
      if (язык !== 'ky' && !номера) return Promise.resolve();
      return fetch('ky.json', { cache: 'no-store' })
        .then(function (r) { return r.ok ? r.json() : {}; })
        .then(function (д) {
          д = д || {};
          ШАБЛОНЫ = (д['__шаблоны__'] || []).map(function (ш) {
            return { re: new RegExp(ш.re), t: ш.t, n: ш.n };
          });
          delete д['__шаблоны__'];
          (д['__имена__'] || []).forEach(function (и) { ИМЕНА[и] = true; });
          delete д['__имена__'];
          СЛОВАРЬ = д;
        })
        .catch(function () { СЛОВАРЬ = {}; });
    },
    т: т,
    перевестиРазметку: перевестиРазметку,
    строкПереведено: function () { return СЛОВАРЬ ? Object.keys(СЛОВАРЬ).length : 0; },
    промахи: function () { return ПРОМАХИ; }
  };
  шапка();
})();
